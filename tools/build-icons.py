#!/usr/bin/env python3
"""
Rebuild the bundled Material Symbols subset and the PHP-side whitelist.

The icon font is a ligature font: the markup is `<span class="hsw-ic">star</span>`
and the font turns the word into a glyph. A subset must therefore keep BOTH the
latin letters (the ligature input) and the icon glyphs (the output) — passing
only `--text` keeps 28 glyphs and every icon turns into raw text.

Two artefacts are produced:
  assets/fonts/material-symbols.woff2   the subset itself
  includes/class-hsw-icon-set.php       the exact glyph list, so HSW_Helpers::icon()
                                        can refuse to print a name the font cannot draw

Usage:
    python tools/build-icons.py <full-MaterialSymbolsOutlined.woff2>

Get the full variable font from
https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200
and download the fonts.gstatic.com woff2 it points to (~4 MB).
"""
import io
import os
import subprocess
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = os.path.join(ROOT, "tools", "_icons.txt")
OUT = os.path.join(ROOT, "assets", "fonts", "material-symbols.woff2")
PHP = os.path.join(ROOT, "includes", "class-hsw-icon-set.php")

# The ligature engine needs the latin alphabet to spell the names out.
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_ -"


def main(src):
    names = sorted(set(io.open(NAMES, encoding="utf-8").read().split()))
    full = TTFont(src)
    order = set(full.getGlyphOrder())

    keep, unknown = [], []
    for n in names:
        (keep if n in order else unknown).append(n)

    if unknown:
        print("!! names with no glyph in the source font (dropped): " + " ".join(unknown))

    glyphs = []
    for n in keep:
        glyphs.append(n)
        if n + ".fill" in order:
            glyphs.append(n + ".fill")

    cmd = [
        sys.executable, "-m", "fontTools.subset", src,
        "--glyphs=" + ",".join(glyphs),
        "--text=" + " ".join(keep) + " " + ALPHABET,
        "--layout-features=rclt,rlig",
        "--no-layout-closure",
        "--no-hinting",
        "--glyph-names",
        "--flavor=woff2",
        "--drop-tables+=DSIG",
        "--output-file=" + OUT,
    ]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr[-800:])

    g = TTFont(OUT)
    size = os.path.getsize(OUT) / 1024
    print(f"icons requested: {len(names)}  glyphs kept: {len(g.getGlyphOrder())}  size: {size:.1f}KB")
    print("axes:", [(a.axisTag, a.minValue, a.maxValue) for a in g["fvar"].axes])

    write_php(keep, len(g.getGlyphOrder()), size)


def write_php(names, glyphs, size):
    """Emit the whitelist consumed by HSW_Helpers::icon()."""
    rows, line = [], "\t\t\t\t"
    for n in names:
        piece = "'" + n + "', "
        if len(line) + len(piece) > 100:
            rows.append(line.rstrip())
            line = "\t\t\t\t"
        line += piece
    if line.strip():
        rows.append(line.rstrip().rstrip(","))

    body = "\n".join(rows)
    php = """<?php
/**
 * Auto-generated by tools/build-icons.py - do not edit by hand.
 *
 * Every name below has a glyph in assets/fonts/material-symbols.woff2
 * ({glyphs} glyphs, {size:.1f} KB). HSW_Helpers::icon() refuses to render
 * anything outside this list, so a typo or an unbundled icon can no longer
 * leak as English text.
 *
 * @package HamiShop_Elementor_Widgets
 */

defined( 'ABSPATH' ) || exit;

class HSW_Icon_Set {{

\t/**
\t * Names the bundled subset can draw.
\t *
\t * @return string[]
\t */
\tpublic static function names() {{
\t\tstatic $names = null;
\t\tif ( null === $names ) {{
\t\t\t$names = array(
{body}
\t\t\t);
\t\t}}
\t\treturn $names;
\t}}

\t/**
\t * Whether the bundled font has a glyph for this name.
\t *
\t * @param string $name Glyph name.
\t * @return bool
\t */
\tpublic static function has( $name ) {{
\t\tstatic $map = null;
\t\tif ( null === $map ) {{
\t\t\t$map = array_fill_keys( self::names(), true );
\t\t}}
\t\treturn isset( $map[ $name ] );
\t}}
}}
""".format(glyphs=glyphs, size=size, body=body)
    io.open(PHP, "w", encoding="utf-8", newline="\n").write(php)
    print("wrote includes/class-hsw-icon-set.php (%d names)" % len(names))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: build-icons.py <full-woff2>")
    main(sys.argv[1])
