#!/usr/bin/env python3
"""
Turn the icon font's glyph outlines into SVG path data.

The plugin used to ship a 94 KB Material Symbols subset and render icons as
`<span class="hsw-ic">add</span>` ligatures. A font request for a dozen visible
glyphs is a bad trade: it is a separate connection, it flashes text before the
font lands, and the browser has to run the ligature lookup for every icon.

This script walks the same subset and writes the outlines instead, so the
runtime can print a `<symbol>` for the icons a page actually rendered.

Output:
  includes/class-hsw-icon-paths.php   name => path, plus name.fill when present

Usage:
    python tools/build-sprite.py [path/to/subset.woff2]
"""
import io
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.misc.transform import Transform
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets/fonts/material-symbols.woff2")
NAMES = os.path.join(ROOT, "tools/_icons.txt")
OUT = os.path.join(ROOT, "includes/class-hsw-icon-paths.php")

font = TTFont(SRC)
glyphs = font.getGlyphSet()
order = set(font.getGlyphOrder())

# Material Symbols is drawn on a 960 unit grid with the baseline at 0 and the
# glyph sitting above it, so the SVG viewBox is "0 -960 960 960" and every
# y coordinate has to be flipped.
UPEM = font["head"].unitsPerEm
ASC = font["hhea"].ascent


def path(name):
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(pen, Transform(1, 0, 0, -1, 0, 0)))
    return pen.getCommands()


names = io.open(NAMES, encoding="utf-8").read().split()
data = {}
missing = []

for name in sorted(set(names)):
    if name not in order:
        missing.append(name)
        continue
    data[name] = path(name)
    if name + ".fill" in order:
        data[name + ".fill"] = path(name + ".fill")

if missing:
    print("missing glyphs:", missing)

lines = [
    "<?php",
    "/**",
    " * Icon outlines — generated by tools/build-sprite.py, do not edit by hand.",
    " *",
    " * Each entry is the SVG path data for one Material Symbols glyph, drawn on",
    " * the font's %d unit grid with the y axis already flipped, so it can be" % UPEM,
    ' * dropped into a symbol with viewBox="0 -%d %d %d".' % (ASC, UPEM, UPEM),
    " *",
    " * @package HamiShop_Elementor_Widgets",
    " */",
    "",
    "defined( 'ABSPATH' ) || exit;",
    "",
    "return array(",
]
for key in sorted(data):
    lines.append("\t'%s' => '%s'," % (key, data[key].replace("'", "\\'")))
lines.append(");")
lines.append("")

io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("glyphs:", len(data), "bytes:", os.path.getsize(OUT))
